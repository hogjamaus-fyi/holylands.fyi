function updateMeta(selector, content) {
  const element = document.querySelector(selector);
  if (element && content) {
    element.setAttribute('content', content);
  }
}

function setText(contentMap) {
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    const value = contentMap[key];
    if (value) {
      node.innerHTML = value;
    }
  });
}

function getValidLanguage(lang) {
  return translations[lang] ? lang : null;
}

function updateLanguageQuery(lang) {
  const url = new URL(window.location.href);
  url.searchParams.set('lang', lang);
  window.history.replaceState({}, '', url);
}

function updateLocalizedLinks(lang) {
  document.querySelectorAll('a[href]').forEach((link) => {
    const href = link.getAttribute('href');

    if (!href || href.startsWith('#') || href.startsWith('mailto:') || href.startsWith('tel:')) {
      return;
    }

    const url = new URL(href, window.location.href);

    if (url.origin !== window.location.origin) {
      return;
    }

    url.searchParams.set('lang', lang);

    if (href.startsWith('/')) {
      link.setAttribute('href', `${url.pathname}${url.search}${url.hash}`);
      return;
    }

    if (/^https?:/i.test(href)) {
      link.setAttribute('href', url.toString());
      return;
    }

    link.setAttribute('href', `${url.pathname.split('/').pop() || ''}${url.search}${url.hash}`);
  });
}

function applyLanguage(lang) {
  const page = document.body.dataset.page;
  const language = translations[lang] || translations.en;
  const pageContent = language.pages[page];

  if (!pageContent) {
    return;
  }

  document.documentElement.lang = lang;
  document.documentElement.dir = language.dir;
  document.body.dir = language.dir;
  document.body.dataset.lang = lang;
  document.title = pageContent.title;

  setText(pageContent.text);

  updateMeta('meta[name="description"]', pageContent.description);
  updateMeta('meta[property="og:locale"]', pageContent.locale);
  updateMeta('meta[property="og:title"]', pageContent.ogTitle);
  updateMeta('meta[property="og:description"]', pageContent.ogDescription);
  updateMeta('meta[property="og:image:alt"]', pageContent.ogImageAlt);
  updateMeta('meta[name="twitter:title"]', pageContent.twitterTitle);
  updateMeta('meta[name="twitter:description"]', pageContent.twitterDescription);
  updateMeta('meta[name="twitter:image:alt"]', pageContent.twitterImageAlt);

  const nav = document.querySelector('.top-nav');
  if (nav && pageContent.navLabel) {
    nav.setAttribute('aria-label', pageContent.navLabel);
  }

  const sharedFlourishing = document.querySelector('.shared-flourishing');
  if (sharedFlourishing && pageContent.sharedFlourishingLabel) {
    sharedFlourishing.setAttribute('aria-label', pageContent.sharedFlourishingLabel);
  }

  const plan = document.querySelector('.star-plan');
  if (plan && pageContent.planLabelAria) {
    plan.setAttribute('aria-label', pageContent.planLabelAria);
  }

  const schema = document.getElementById('page-schema');
  if (schema) {
    const json = JSON.parse(schema.textContent);
    if (pageContent.schemaDescription) {
      json.description = pageContent.schemaDescription;
    }
    if (pageContent.schemaHeadline) {
      json.headline = pageContent.schemaHeadline;
    }
    schema.textContent = JSON.stringify(json, null, 2);
  }

  document.querySelectorAll('.language-switcher button').forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  updateLocalizedLinks(lang);
  updateLanguageQuery(lang);
  localStorage.setItem('holylands-language', lang);
}

function createSwitcher(initialLang) {
  const language = translations[initialLang] || translations.en;
  const wrapper = document.createElement('div');
  wrapper.className = 'language-switcher';
  wrapper.setAttribute('role', 'group');
  wrapper.setAttribute('aria-label', language.switcherLabel);

  const title = document.createElement('span');
  title.className = 'language-switcher-label';
  title.textContent = language.switcherTitle;
  wrapper.appendChild(title);

  ['ar', 'he', 'en'].forEach((lang) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.dataset.lang = lang;
    button.textContent = lang;
    button.setAttribute('aria-pressed', String(lang === initialLang));
    button.addEventListener('click', () => {
      applyLanguage(lang);
      const current = translations[lang] || translations.en;
      wrapper.setAttribute('aria-label', current.switcherLabel);
      title.textContent = current.switcherTitle;
    });
    wrapper.appendChild(button);
  });

  document.body.appendChild(wrapper);
}

const queryLanguage = getValidLanguage(new URLSearchParams(window.location.search).get('lang'));
const storedLanguage = getValidLanguage(localStorage.getItem('holylands-language'));
const initialLanguage = queryLanguage || storedLanguage || 'en';

createSwitcher(initialLanguage);
applyLanguage(initialLanguage);